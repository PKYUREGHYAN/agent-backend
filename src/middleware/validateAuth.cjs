// ==========================================
// USERNAME VALIDATION
// ==========================================

const validateUsername = (username) => {

    // ------------------------------------------
    // REQUIRED
    // ------------------------------------------

    if (!username) {
        return "Username-ը պարտադիր է";
    }


    // ------------------------------------------
    // TRIM
    // ------------------------------------------

    const cleanUsername =
        username.trim();


    // ------------------------------------------
    // MIN LENGTH
    // ------------------------------------------

    if (cleanUsername.length < 3) {
        return "Username-ը պետք է ունենա առնվազն 3 նիշ";
    }


    // ------------------------------------------
    // MAX LENGTH
    // ------------------------------------------

    if (cleanUsername.length > 30) {
        return "Username-ը կարող է ունենալ առավելագույնը 30 նիշ";
    }


    // ------------------------------------------
    // ALLOWED CHARACTERS
    // ------------------------------------------

    if (!/^[a-zA-Z0-9_]+$/.test(cleanUsername)) {
        return "Username-ը կարող է պարունակել միայն տառեր, թվեր և _";
    }


    // ------------------------------------------
    // VALID
    // ------------------------------------------

    return null;
};


// ==========================================
// EMAIL VALIDATION
// ==========================================

const validateEmail = (email) => {

    // ------------------------------------------
    // REQUIRED
    // ------------------------------------------

    if (!email) {
        return "Email-ը պարտադիր է";
    }


    // ------------------------------------------
    // TRIM
    // ------------------------------------------

    const cleanEmail =
        email.trim();


    // ------------------------------------------
    // EMAIL MUST BE LOWERCASE
    // ------------------------------------------

    if (cleanEmail !== cleanEmail.toLowerCase()) {
        return "Email-ը պետք է գրվի ամբողջությամբ փոքրատառերով";
    }


    // ------------------------------------------
    // MAX LENGTH
    // ------------------------------------------

    if (cleanEmail.length > 254) {
        return "Email-ը չափազանց երկար է";
    }


    // ------------------------------------------
    // EMAIL FORMAT
    // ------------------------------------------

    const emailRegex =
        /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

    if (!emailRegex.test(cleanEmail)) {
        return "Email-ի ձևաչափը սխալ է";
    }


    // ------------------------------------------
    // VALID
    // ------------------------------------------

    return null;
};


// ==========================================
// PASSWORD VALIDATION
// ==========================================

const validatePassword = (password) => {

    // ------------------------------------------
    // REQUIRED
    // ------------------------------------------

    if (!password) {
        return "Գաղտնաբառը պարտադիր է";
    }


    // ------------------------------------------
    // MIN LENGTH
    // ------------------------------------------

    if (password.length < 8) {
        return "Գաղտնաբառը պետք է ունենա առնվազն 8 նիշ";
    }


    // ------------------------------------------
    // MAX 72 BYTES FOR BCRYPT
    // ------------------------------------------

    if (
        Buffer.byteLength(
            password,
            "utf8"
        ) > 72
    ) {
        return "Գաղտնաբառը չափազանց երկար է";
    }


    // ------------------------------------------
    // UPPERCASE
    // ------------------------------------------

    if (!/[A-Z]/.test(password)) {
        return "Գաղտնաբառը պետք է պարունակի առնվազն մեկ մեծատառ";
    }


    // ------------------------------------------
    // LOWERCASE
    // ------------------------------------------

    if (!/[a-z]/.test(password)) {
        return "Գաղտնաբառը պետք է պարունակի առնվազն մեկ փոքրատառ";
    }


    // ------------------------------------------
    // NUMBER
    // ------------------------------------------

    if (!/[0-9]/.test(password)) {
        return "Գաղտնաբառը պետք է պարունակի առնվազն մեկ թիվ";
    }


    // ------------------------------------------
    // SPECIAL CHARACTER
    // ------------------------------------------

    if (
        !/[!@#$%^&*()_+\-=[\]{};':"\\|,.<>/?`~]/.test(password)
) {
    return "Գաղտնաբառը պետք է պարունակի առնվազն մեկ հատուկ նշան";
}


// ------------------------------------------
// VALID
// ------------------------------------------

return null;
};


// ==========================================
// CONFIRM PASSWORD VALIDATION
// ==========================================

const validateConfirmPassword = (
    password,
    confirmPassword
) => {

    // ------------------------------------------
    // REQUIRED
    // ------------------------------------------

    if (!confirmPassword) {
        return "Գաղտնաբառի հաստատումը պարտադիր է";
    }


    // ------------------------------------------
    // PASSWORD MATCH
    // ------------------------------------------

    if (password !== confirmPassword) {
        return "Գաղտնաբառերը չեն համընկնում";
    }


    // ------------------------------------------
    // VALID
    // ------------------------------------------

    return null;
};


// ==========================================
// EXPORT
// ==========================================

module.exports = {
    validateUsername,
    validateEmail,
    validatePassword,
    validateConfirmPassword,
};

